#!/usr/bin/env node
'use strict';

const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const SRC = path.join(ROOT, 'public/css/src');
const OUT = path.join(ROOT, 'public/css/app.css');
const HEADER = '/* GENERATED by scripts/build-css.js. Edit public/css/src/, not this file. */\n';

function walk(dir, acc = []) {
  if (!fs.existsSync(dir)) return acc;
  for (const ent of fs.readdirSync(dir, { withFileTypes: true })) {
    const p = path.join(dir, ent.name);
    if (ent.isDirectory()) walk(p, acc);
    else if (ent.isFile() && ent.name.endsWith('.css')) acc.push(p);
  }
  return acc;
}

function rel(file) {
  return path.relative(SRC, file).split(path.sep).join('/');
}

function sources() {
  return walk(SRC).sort((a, b) => rel(a).localeCompare(rel(b), 'en', { numeric: true }));
}

function build() {
  const files = sources();
  if (!files.length) throw new Error('No CSS sources found in ' + SRC);
  let out = HEADER;
  for (const file of files) {
    let body = fs.readFileSync(file, 'utf8');
    if (!body.endsWith('\n')) body += '\n';
    out += `/* --- src/${rel(file)} --- */\n`;
    out += body;
  }
  return out;
}

function main() {
  const check = process.argv.includes('--check');
  const css = build();
  if (check) {
    const current = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : '';
    if (current !== css) {
      console.error('public/css/app.css is out of date. Run: npm run build:css');
      process.exit(1);
    }
    console.log('check:css ok (' + sources().length + ' files)');
    return;
  }
  fs.mkdirSync(path.dirname(OUT), { recursive: true });
  fs.writeFileSync(OUT, css);
  console.log('wrote public/css/app.css from ' + sources().length + ' files');
}

main();
