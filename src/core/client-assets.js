/**
 * Browser side of feature folders.
 *
 *   /features/client.js      generated: imports /features/<id>/ws.js for every feature with client/ws.js
 *   /features/features.css   generated: every feature's client/*.css, concatenated in feature order
 *   /features/<id>/<file>    src/features/<id>/client/<file>
 */
const fs = require('fs');
const path = require('path');
const crypto = require('crypto');
const features = require('./features');

const TYPES = { '.js': 'text/javascript; charset=utf-8', '.css': 'text/css; charset=utf-8', '.svg': 'image/svg+xml', '.png': 'image/png', '.json': 'application/json' };

function clientJs() {
  const lines = ['// Generated by src/core/client-assets.js: loads every feature\'s room message handlers.'];
  for (const f of features.list()) if (f.clientWs) lines.push(`import '/features/${f.name}/ws.js';`);
  return lines.join('\n') + '\n';
}

function clientCss() {
  const parts = [];
  for (const f of features.list()) {
    for (const file of f.clientCss) {
      parts.push(`/* ---- ${f.name}/${file} ---- */\n` + fs.readFileSync(path.join(f.dir, 'client', file), 'utf8'));
    }
  }
  return parts.join('\n');
}

function send(req, res, body, type) {
  const etag = 'W/"' + crypto.createHash('sha1').update(body).digest('hex').slice(0, 16) + '"';
  const headers = { 'Content-Type': type, 'Cache-Control': 'no-cache', ETag: etag, 'X-Content-Type-Options': 'nosniff' };
  if (req.headers['if-none-match'] === etag) { res.writeHead(304, headers); return res.end(); }
  headers['Content-Length'] = Buffer.byteLength(body);
  res.writeHead(200, headers);
  res.end(req.method === 'HEAD' ? undefined : body);
}

/** Returns true when the request was a /features/ asset (answered, or 404). */
function serve(req, res, urlPath) {
  if (!urlPath.startsWith('/features/')) return false;
  if (urlPath === '/features/client.js') { send(req, res, clientJs(), TYPES['.js']); return true; }
  if (urlPath === '/features/features.css') { send(req, res, clientCss(), TYPES['.css']); return true; }
  const m = urlPath.match(/^\/features\/([A-Za-z0-9_-]+)\/([A-Za-z0-9_.-]+)$/);
  const f = m && !m[2].startsWith('.') && features.list().find((x) => x.name === m[1]);
  const file = f && path.join(f.dir, 'client', m[2]);
  const type = file && TYPES[path.extname(file).toLowerCase()];
  if (!type || !fs.existsSync(file) || !fs.statSync(file).isFile()) {
    res.writeHead(404, { 'Content-Type': 'text/plain' });
    res.end('Not found');
    return true;
  }
  send(req, res, fs.readFileSync(file), type);
  return true;
}

module.exports = { serve, clientJs, clientCss };
